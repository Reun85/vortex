//! Generates `scripting/Delta.Scripting/Generated/Engine.g.cs`: a C# mirror
//! of every `#[reflect(script)]` type, with explicit offsets taken from the
//! Rust layout, so padding and alignment are identical by construction.
//!
//! Run `cargo xtask gen-csharp` after changing a script-visible type. A test
//! reruns the generator and fails if the committed file differs.

use std::fmt::Write;

use delta::{
    KeyCode,
    World,
    reflect::{FieldType, ReflectId, TypeReflect, TypeRegistry},
};

use crate::register_script_types;

/// Rust math types that map to `System.Numerics` instead of being generated.
const ALIASES: [(&str, &str); 4] = [
    ("vortex::Vec2", "Vector2"),
    ("vortex::Vec3", "Vector3"),
    ("vortex::Vec4", "Vector4"),
    ("vortex::Quat", "Quaternion"),
];

fn alias(name: &str) -> Option<&'static str> {
    ALIASES.iter().find(|(n, _)| *n == name).map(|(_, c)| *c)
}

fn last_segment(name: &str) -> &str {
    name.rsplit("::").next().unwrap_or(name)
}

fn pascal(snake: &str) -> String {
    snake
        .split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_uppercase().collect::<String>() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn scalar(ty: &FieldType) -> Option<&'static str> {
    Some(match ty {
        FieldType::Bool => "bool",
        FieldType::I8 => "sbyte",
        FieldType::I16 => "short",
        FieldType::I32 => "int",
        FieldType::I64 => "long",
        FieldType::U8 => "byte",
        FieldType::U16 => "ushort",
        FieldType::U32 => "uint",
        FieldType::U64 => "ulong",
        FieldType::F32 => "float",
        FieldType::F64 => "double",
        FieldType::Entity => "Entity",
        _ => return None,
    })
}

fn struct_name(
    registry: &TypeRegistry,
    id: ReflectId,
    resource: bool,
) -> String {
    let name = &*registry.get(id).name;
    match alias(name) {
        Some(a) => a.to_owned(),
        None if resource => format!("{}Data", last_segment(name)),
        None => last_segment(name).to_owned(),
    }
}

fn write_struct(
    out: &mut String,
    registry: &TypeRegistry,
    t: &TypeReflect,
    id: ReflectId,
    kind: Kind,
) {
    let name = struct_name(registry, id, matches!(kind, Kind::Resource));
    let has_fixed = t
        .fields
        .iter()
        .any(|f| matches!(f.ty, FieldType::Array { .. }));
    writeln!(out, "/// <summary>Mirror of <c>{}</c>.</summary>", t.name)
        .unwrap();
    writeln!(
        out,
        "[StructLayout(LayoutKind.Explicit, Size = {})]",
        t.size
    )
    .unwrap();
    match kind {
        Kind::Component => {
            writeln!(out, "[EngineComponent(\"{}\")]", t.name).unwrap()
        }
        Kind::Resource => {
            writeln!(out, "[EngineResource(\"{}\")]", t.name).unwrap()
        }
        Kind::Plain => {}
    }
    let unsafe_kw = if has_fixed { "unsafe " } else { "" };
    let iface = if matches!(kind, Kind::Component) {
        " : IComponent"
    } else {
        ""
    };
    writeln!(out, "public {unsafe_kw}struct {name}{iface}\n{{").unwrap();
    for f in t.fields.iter() {
        let field = pascal(&f.name);
        write!(out, "    [FieldOffset({})] public ", f.offset).unwrap();
        match &f.ty {
            FieldType::Array { elem, len, .. } => {
                let e = scalar(elem).unwrap_or_else(|| {
                    panic!("{}.{}: arrays of {elem:?}", t.name, f.name)
                });
                writeln!(out, "fixed {e} {field}[{len}];").unwrap();
            }
            FieldType::Struct(s) => {
                writeln!(out, "{} {field};", struct_name(registry, *s, false))
                    .unwrap();
            }
            other => {
                let s = scalar(other).unwrap_or_else(|| {
                    panic!("{}.{}: unsupported type {other:?}", t.name, f.name)
                });
                writeln!(out, "{s} {field};").unwrap();
            }
        }
    }
    writeln!(out, "}}\n").unwrap();
}

#[derive(Clone, Copy)]
enum Kind {
    Component,
    Resource,
    Plain,
}

/// The world the generator (and the golden test) describes.
pub fn describe_world() -> World {
    let mut world = World::new();
    register_script_types(&mut world);
    world
}

/// The text of `Engine.g.cs`.
pub fn generate() -> String {
    let world = describe_world();
    let registry = world.reflection();
    let mut types: Vec<(ReflectId, &TypeReflect)> = registry
        .iter()
        .filter(|(_, t)| t.script && alias(&t.name).is_none())
        .collect();
    types.sort_by(|a, b| a.1.name.cmp(&b.1.name));

    let mut out = String::new();
    out.push_str(
        "// <auto-generated>\n\
         // Generated by `cargo xtask gen-csharp` from the Rust definitions.\n\
         // Do not edit: change the Rust type and regenerate.\n\
         // </auto-generated>\n\
         using System.Numerics;\n\
         using System.Runtime.InteropServices;\n\n\
         namespace Delta;\n\n",
    );
    for (id, t) in types {
        let kind = if world.exposed_resources().any(|(n, _)| n == &*t.name) {
            Kind::Resource
        } else if world.components().id_by_name(&t.name).is_some() {
            Kind::Component
        } else {
            Kind::Plain
        };
        write_struct(&mut out, registry, t, id, kind);
    }
    out.push_str(
        "/// <summary>Keys and mouse buttons. Mirrors <c>delta::KeyCode</c>.</summary>\n\
         public enum KeyCode : ushort\n{\n",
    );
    for (i, (name, value)) in KeyCode::ALL.iter().enumerate() {
        let comma = if i + 1 < KeyCode::ALL.len() { "," } else { "" };
        writeln!(out, "    {name} = {value}{comma}").unwrap();
    }
    out.push_str("}\n");
    out
}
